/* Biome sprite selector — called once per drawWorld() frame */
function getBiomeSprites(depth){
  if(!depth||depth<=10)  return [SPR_FLOOR_HOUSE, SPR_WALL_HOUSE];
  if(depth<=20)          return [SPR_FLOOR_LOWE,  SPR_WALL_LOWE];
  if(depth<=30)          return [SPR_FLOOR_PARK,  SPR_WALL_PARK];
  if(depth<=40)          return [SPR_FLOOR_VASTCO,SPR_WALL_VASTCO];
  if(depth<=50)          return [SPR_FLOOR_SOCCER,SPR_WALL_SOCCER];
  if(depth<=60)          return [SPR_FLOOR_SCHOOL,SPR_WALL_SCHOOL];
  if(depth<=70)          return [SPR_FLOOR_RESTO, SPR_WALL_RESTO];
  if(depth<=80)          return [SPR_FLOOR_IDKEA, SPR_WALL_IDKEA];
  if(depth<=90)          return [SPR_FLOOR_HOOD,  SPR_WALL_HOOD];
  return                        [SPR_FLOOR_HOA,   SPR_WALL_HOA];
}
