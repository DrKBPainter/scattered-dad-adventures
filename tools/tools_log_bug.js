#!/usr/bin/env node
/**
 * tools_log_bug.js — append a structured entry to bugs/BUG_LOG.md
 *
 * Usage:
 *   node tools/tools_log_bug.js \
 *     --title "Short description" \
 *     --desc  "Full detail" \
 *     --file  "js/game.js" \
 *     --status open|resolved \
 *     [--repro "Steps to reproduce"] \
 *     [--fix   "How it was fixed (for resolved bugs)"]
 *
 * Statuses: open | resolved | wontfix
 *
 * The script:
 *   1. Reads bugs/BUG_LOG.md
 *   2. Determines the next BUG-NNN id
 *   3. Inserts a new row in the summary table
 *   4. Appends a full detail block under the correct section header
 *   5. Writes the file back
 */

"use strict";
const fs   = require("fs");
const path = require("path");

// ── parse args ────────────────────────────────────────────────────────────────
const argv = process.argv.slice(2);
function flag(name, fallback = "") {
  const i = argv.indexOf("--" + name);
  return i !== -1 && argv[i + 1] !== undefined ? argv[i + 1] : fallback;
}

const title  = flag("title");
const desc   = flag("desc");
const file   = flag("file", "unknown");
const status = flag("status", "open").toLowerCase();
const repro  = flag("repro", "");
const fix    = flag("fix",   "");

if (!title || !desc) {
  console.error("Usage: node tools/tools_log_bug.js --title '...' --desc '...' [--file '...'] [--status open|resolved] [--repro '...'] [--fix '...']");
  process.exit(1);
}

if (!["open", "resolved", "wontfix"].includes(status)) {
  console.error("--status must be one of: open, resolved, wontfix");
  process.exit(1);
}

// ── locate the log file ───────────────────────────────────────────────────────
// Support running from project root OR from the tools/ subdirectory
const candidates = [
  path.join(process.cwd(), "bugs", "BUG_LOG.md"),
  path.join(__dirname, "..", "bugs", "BUG_LOG.md"),
];
const logPath = candidates.find(fs.existsSync);
if (!logPath) {
  console.error("Cannot find bugs/BUG_LOG.md — run from the project root.");
  process.exit(1);
}

let content = fs.readFileSync(logPath, "utf8");

// ── derive next id ────────────────────────────────────────────────────────────
const ids   = [...content.matchAll(/BUG-(\d+)/g)].map(m => parseInt(m[1], 10));
const nextN = ids.length ? Math.max(...ids) + 1 : 1;
const id    = "BUG-" + String(nextN).padStart(3, "0");
const today = new Date().toISOString().slice(0, 10);

// ── build table row ───────────────────────────────────────────────────────────
const tableRow = `| ${id} | ${title} | \`${file}\` | ${status} | ${today} |`;

// ── build detail block ────────────────────────────────────────────────────────
let detail = `\n### ${id} — ${title}\n\n`;
detail += `- **File:** \`${file}\`\n`;
detail += `- **Status:** ${status}\n`;
detail += `- **Logged:** ${today}\n\n`;
detail += `**Description:** ${desc}\n`;
if (repro)  detail += `\n**Repro steps:** ${repro}\n`;
if (fix)    detail += `\n**Fix:** ${fix}\n`;
detail += `\n---\n`;

// ── insert table row ──────────────────────────────────────────────────────────
// Append after the last existing table row (or after the header separator)
const tableHeaderRe = /(\| ID \| Title \| File \| Status \| Logged \|\n\|[-| ]+\|\n)/;
if (tableHeaderRe.test(content)) {
  // find the end of the last table row before the blank line
  const lastRowRe = /(\| BUG-\d+ \|[^\n]+\n)(?=\n|---)/;
  if (lastRowRe.test(content)) {
    content = content.replace(lastRowRe, `$1${tableRow}\n`);
  } else {
    // table exists but is empty — insert right after separator line
    content = content.replace(tableHeaderRe, `$1${tableRow}\n`);
  }
} else {
  console.warn("Warning: could not locate summary table — row will be appended at top of file.");
}

// ── insert detail block ───────────────────────────────────────────────────────
const openHeader     = "## Open Bugs";
const resolvedHeader = "## Resolved Bugs";
const anchor         = "*Generated by tools/tools_log_bug.js";

if (status === "open") {
  // Replace placeholder if still present
  if (content.includes("*(none yet)*\n\n---")) {
    content = content.replace(
      `${openHeader}\n\n*(none yet)*\n\n---`,
      `${openHeader}\n${detail}`
    );
  } else {
    // Append before Resolved Bugs section
    content = content.replace(resolvedHeader, detail + resolvedHeader);
  }
} else {
  // resolved / wontfix
  if (content.includes("*(none yet)*\n\n---\n\n*Generated")) {
    content = content.replace(
      `${resolvedHeader}\n\n*(none yet)*\n\n---\n\n${anchor}`,
      `${resolvedHeader}\n${detail}\n${anchor}`
    );
  } else {
    content = content.replace(anchor, detail + anchor);
  }
}

fs.writeFileSync(logPath, content);
console.log(`Logged ${id}: "${title}" [${status}] in bugs/BUG_LOG.md`);
